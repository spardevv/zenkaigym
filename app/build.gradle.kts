    namespace = "com.zenkaigym"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.zenkaigym"
        minSdk = 24
        targetSdk = 35
        // Em release o workflow passa -PversionCode/-PversionName derivados da tag (vX.Y.Z).
